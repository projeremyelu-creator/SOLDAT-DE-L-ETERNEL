def ouvrir(b, mode="owner", w=390, h=844, scheme="light"):
    ctx = b.new_context(viewport={"width": w, "height": h}, color_scheme=scheme, locale="fr-FR", timezone_id="Africa/Abidjan", has_touch=False)
    ctx.add_init_script(f"window.__MODE = {json.dumps(mode)};\n" + MOCK)
    p = ctx.new_page()
    p.on("pageerror", lambda e: errs.append(f"[{mode} {w}] pageerror: {e}"))
    p.on("console", lambda m: errs.append(f"[{mode} {w}] console.{m.type}: {m.text}") if m.type == "error" and "ERR_" not in m.text and "404" not in m.text and "_blob" not in m.text else None)
    ctx.route("**/fonts.googleapis.com/**", lambda r: r.abort())
    ctx.route("https://wa.me/**", lambda r: r.fulfill(body="wa"))
    p.route("https://cdn.jsdelivr.net/npm/qrcode-generator@1.4.4/qrcode.js", lambda r: r.fulfill(path=str(QR), content_type="application/javascript"))
    p.route("https://cdn.jsdelivr.net/npm/jszip@3.10.1/dist/jszip.min.js", lambda r: r.fulfill(path=str(ZIP), content_type="application/javascript"))
    p.goto(URL); p.wait_for_timeout(700)
    return ctx, p
def debord(p, tag):
    sw = p.evaluate("[document.documentElement.scrollWidth, document.documentElement.clientWidth]")
    if sw[0] > sw[1]: errs.append(f"DÉBORDEMENT {tag}: {sw}")
def doc(p, path): return json.loads(p.evaluate(f"JSON.stringify(window.__store.get({json.dumps(path)}) || null)"))
def docs(p, prefix): return json.loads(p.evaluate(f"JSON.stringify([...window.__store.entries()].filter(([k]) => k.startsWith({json.dumps(prefix)})))"))
