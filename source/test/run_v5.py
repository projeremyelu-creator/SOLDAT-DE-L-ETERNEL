def fichier(p, nom):
    data = p.evaluate(f"window.__files[{json.dumps(nom)}]")
    return base64.b64decode(data.split(",", 1)[1]) if data else b""
def qr_de(png):
    im = cv2.imdecode(np.frombuffer(png, np.uint8), cv2.IMREAD_COLOR)
    t, _, _ = cv2.QRCodeDetector().detectAndDecode(im)
    return t

